const INDEX = new Map<string, number>(SOURCES.map((source, index) => [source, index]));

export function adminWelcomeImageText(source: string, language: UiLanguage): string | null {
  const index = INDEX.get(source);
  if (index === undefined) return null;
  return VALUES[language][index] ?? SOURCES[index];
}

for (const [language, entries] of Object.entries(VALUES)) {
  if (entries.length !== SOURCES.length || entries.some((entry) => !entry.trim())) {
    throw new Error(`Incomplete welcome image translations for ${language}`);
  }
}
