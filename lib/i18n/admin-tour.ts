const MAP: Record<UiLanguage, Record<AdminTourText, string>> = Object.fromEntries(
  Object.entries(VALUES).map(([language, values]) => {
    if (values.length !== ENGLISH.length) throw new Error(`Incomplete admin tour translations for ${language}`);
    return [language, Object.fromEntries(ENGLISH.map((source, index) => [source, values[index]]))];
  }),
) as Record<UiLanguage, Record<AdminTourText, string>>;

export function adminTourText(source: string, language: UiLanguage): string {
  return MAP[language][source as AdminTourText] ?? source;
}

